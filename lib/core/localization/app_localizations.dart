class AppLocaleController extends ValueNotifier<Locale> {
  AppLocaleController._() : super(const Locale('en'));

  static final instance = AppLocaleController._();

  Future<void> load() async {
    final preferences = await SharedPreferences.getInstance();
    value = Locale(preferences.getString('language_code') ?? 'en');
  }

  Future<void> setLanguage(String code) async {
    value = Locale(code);
    final preferences = await SharedPreferences.getInstance();
    await preferences.setString('language_code', code);
  }
}

